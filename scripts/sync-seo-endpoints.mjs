#!/usr/bin/env node
/**
 * Generates the static SEO endpoints that must exist BEFORE JavaScript runs:
 *
 *   public/sitemap.xml   – sitemap index pointing at the live Supabase edge
 *                          functions (they build the URL lists from the DB)
 *   public/robots.txt    – crawler policy + sitemap references
 *
 * Why a script: the previous public/sitemap.xml pointed at
 * `https://<frontend-domain>/functions/v1/sitemap`, but edge functions are
 * served from `https://<project-ref>.supabase.co/functions/v1/...`. Search
 * Console was therefore given a sitemap index full of dead URLs.
 *
 * Runs automatically via the `prebuild`/`predev` npm hooks, so the files stay
 * in sync with VITE_SUPABASE_URL in .env.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** Minimal .env reader (no dependency on dotenv). */
function envValue(key) {
  if (process.env[key]) return process.env[key];
  const envPath = resolve(root, ".env");
  if (!existsSync(envPath)) return undefined;
  for (const line of readFileSync(envPath, "utf8").split("\n")) {
    const match = line.match(new RegExp(`^\\s*${key}\\s*=\\s*"?([^"\\n]*)"?\\s*$`));
    if (match) return match[1].trim();
  }
  return undefined;
}

const siteUrl = (envValue("VITE_SITE_URL") || "https://newssparkle.lovable.app").replace(/\/$/, "");
const supabaseUrl = (envValue("VITE_SUPABASE_URL") || "").replace(/\/$/, "");

if (!supabaseUrl) {
  console.warn("[seo] VITE_SUPABASE_URL is not set — writing sitemap without dynamic feeds.");
}

const feeds = supabaseUrl
  ? [
      { loc: `${supabaseUrl}/functions/v1/sitemap`, comment: "all posts, categories, authors and tags" },
      { loc: `${supabaseUrl}/functions/v1/news-sitemap`, comment: "Google News feed — last 48 hours" },
    ]
  : [];

const sitemapIndex = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
  ...feeds.flatMap((f) => [
    `  <!-- ${f.comment} -->`,
    "  <sitemap>",
    `    <loc>${f.loc}</loc>`,
    "  </sitemap>",
  ]),
  "</sitemapindex>",
  "",
].join("\n");

const robots = `# NewsSparkle robots.txt — generated by scripts/sync-seo-endpoints.mjs
User-agent: *
Allow: /
Disallow: /search
Disallow: /404
Disallow: /bookmarks

# Be explicit about the crawlers we care about
User-agent: Googlebot
Allow: /

User-agent: Googlebot-News
Allow: /

User-agent: Googlebot-Image
Allow: /

User-agent: Bingbot
Allow: /

User-agent: GPTBot
Allow: /

User-agent: Google-Extended
Allow: /

User-agent: CCBot
Allow: /

User-agent: PerplexityBot
Allow: /

User-agent: ClaudeBot
Allow: /

User-agent: Twitterbot
Allow: /

User-agent: facebookexternalhit
Allow: /

User-agent: LinkedInBot
Allow: /

User-agent: WhatsApp
Allow: /

Crawl-delay: 1

Sitemap: ${siteUrl}/sitemap.xml
${feeds.map((f) => `Sitemap: ${f.loc}`).join("\n")}
`;

writeFileSync(resolve(root, "public/sitemap.xml"), sitemapIndex, "utf8");
writeFileSync(resolve(root, "public/robots.txt"), robots, "utf8");

// Keep the machine-readable resource links on the same public hosts as the UI.
const llmsPath = resolve(root, "public/llms.txt");
if (existsSync(llmsPath)) {
  const resources = {
    Website: siteUrl,
    "Main Sitemap": `${siteUrl}/sitemap.xml`,
    "News Sitemap": supabaseUrl ? `${supabaseUrl}/functions/v1/news-sitemap` : "Not configured",
    RSS: supabaseUrl ? `${supabaseUrl}/functions/v1/rss` : "Not configured",
  };
  let llms = readFileSync(llmsPath, "utf8");
  for (const [label, value] of Object.entries(resources)) {
    llms = llms.replace(new RegExp(`^- \\*\\*${label}\\*\\*: .*$`, "m"), `- **${label}**: ${value}`);
  }
  writeFileSync(llmsPath, llms, "utf8");
}

console.log(`[seo] sitemap.xml + robots.txt updated (site: ${siteUrl})`);
if (feeds.length) console.log(`[seo] feeds: ${feeds.map((f) => f.loc).join(", ")}`);
